/** Everything south of this latitude is Antarctica. */
const ANTARCTICA_LAT = -66;

const isInside = (lon: number, lat: number, polygon: readonly Point[]) => {
	let inside = false;
	for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
		const [xi, yi] = polygon[i];
		const [xj, yj] = polygon[j];
		if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
	}
	return inside;
};

/** Land lookup on a 1°×1° grid, built once so each animation frame is only array reads. */
export interface LandMask {
	isLand(lon: number, lat: number): boolean;
}

export const buildLandMask = (): LandMask => {
	const WIDTH = 360;
	const HEIGHT = 180;
	const cells = new Uint8Array(WIDTH * HEIGHT);
	for (let row = 0; row < HEIGHT; row++) {
		const lat = 89.5 - row;
		for (let col = 0; col < WIDTH; col++) {
			const lon = col - 179.5;
			const land = lat < ANTARCTICA_LAT || LAND_POLYGONS.some((polygon) => isInside(lon, lat, polygon));
			cells[row * WIDTH + col] = land ? 1 : 0;
		}
	}
	return {
		isLand(lon, lat) {
			const col = Math.floor((((lon + 180) % 360) + 360) % 360);
			const row = Math.min(HEIGHT - 1, Math.max(0, Math.floor(90 - lat)));
			return cells[row * WIDTH + col] === 1;
		},
	};
};
